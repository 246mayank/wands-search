"""Generate docs/DATA_NOTES.md: every fact about WANDS that a later decision depends on."""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import polars as pl

from wands import data
from wands.eval.provenance import git_sha
from wands.eval.qrels import build_qrels
from wands.text import parse_features, split_classes

NOTES_PATH = Path("docs/DATA_NOTES.md")


def render(wands: data.Wands, sha: str) -> str:
    products, queries, labels = wands.products, wands.queries, wands.labels
    per_query = labels.group_by("query_id").agg(
        pl.len().alias("labelled"),
        (pl.col("label") == "Exact").sum().alias("exact"),
        (pl.col("label") == "Partial").sum().alias("partial"),
    )
    pairs = labels.group_by("query_id", "product_id").agg(
        pl.len().alias("n"), pl.col("label").n_unique().alias("distinct")
    )
    duplicated = pairs.filter(pl.col("n") > 1)
    conflicting = duplicated.filter(pl.col("distinct") > 1)
    qrels = build_qrels(labels)
    relevant = sorted(sum(g > 0 for g in judged.values()) for judged in qrels.values())

    raw_classes = products["product_class"].to_list()
    class_counts = Counter(c for raw in raw_classes for c in split_classes(raw))
    query_classes = queries["query_class"].to_list()
    labelled = [c for c in query_classes if c]
    raw_set = set(raw_classes)
    in_raw = sum(c in raw_set for c in labelled)
    in_split = sum(c in class_counts for c in labelled)
    unmatched = sorted({c for c in labelled if c not in class_counts})
    strata = Counter(query_classes)

    key_counts: Counter[str] = Counter()
    for raw in products["product_features"].to_list():
        key_counts.update({key for key, _ in parse_features(raw)})

    nulls = {c: int((products[c] == "").sum()) for c in data.TEXT_COLUMNS}
    label_counts = dict(labels["label"].value_counts().iter_rows())
    multi = sum("|" in c for c in raw_classes)

    def summary(col: str) -> str:
        s = per_query[col]
        return f"{s.min()} / {s.median():g} / {s.max()}"

    lines = [
        "# WANDS data notes",
        "",
        f"Generated by `wands data profile` at commit `{sha}` from WANDS commit `{data.WANDS_COMMIT[:7]}`. "
        "Do not edit by hand.",
        "",
        "## Files",
        "",
        "All three files are UTF-8 and tab-separated, as `read_dataset.ipynb` shows. Three traps:",
        "",
        '- `query.csv` is CSV-quoted: three queries hold an escaped inch mark (`writing desk 48"`). Reading it '
        'with quoting off leaves literal `"""` in the query text.',
        "- `product.csv` has raw inch marks inside fields, so it is read with quoting off.",
        "- The header says `category hierarchy` with a space, though the README says `category_hierarchy`. "
        "`data.load` renames it.",
        "",
        "Checksums: SHA-256 is pinned in `wands/data.py`. On first download each file's git blob id was "
        "also compared with the blob ids GitHub lists for that commit, and all three matched.",
        "",
        f"Rows: {products.height:,} products, {queries.height} queries, {labels.height:,} labels. "
        f"Query ids are not contiguous (max {queries['query_id'].max()}).",
        "",
        "Empty text fields: " + ", ".join(f"`{c}` {n:,}" for c, n in nulls.items()) + ".",
        "",
        "## Labels",
        "",
        f"Overall: Exact {label_counts['Exact']:,}, Partial {label_counts['Partial']:,}, "
        f"Irrelevant {label_counts['Irrelevant']:,}.",
        "",
        "| per query | min / median / max |",
        "|---|---|",
        f"| labelled products | {summary('labelled')} |",
        f"| Exact | {summary('exact')} |",
        f"| Partial | {summary('partial')} |",
        "",
        f"- **Duplicates.** {duplicated.height:,} (query, product) pairs are labelled more than once, in "
        f"{duplicated['query_id'].n_unique()} queries, leaving {sum(len(j) for j in qrels.values()):,} unique "
        f"pairs. {conflicting.height} of them disagree. `build_qrels` keeps the highest gain; with so few "
        "conflicts the rule can't move a mean by much.",
        f"- **No Exact label.** {int((per_query['exact'] == 0).sum())} queries have none, so Exact-only NDCG and "
        "MRR are undefined there. Those metrics skip such queries instead of scoring them 0, and each report "
        "gives the number of queries scored.",
        f"- **Nothing relevant.** {int(((per_query['exact'] + per_query['partial']) == 0).sum())} query has no "
        "Exact or Partial label, so graded NDCG skips it too.",
        f"- **Recall@100 can't reach 1.** The median query has {relevant[len(relevant) // 2]} relevant products "
        f"and the largest has {relevant[-1]:,}, so 100 results can't hold them all. Reports add "
        "`capped_recall@100` (divide by min(relevant, 100)), which is the honest ceiling for a reranker.",
        f"- **Pool depth.** {products.height - labels['product_id'].n_unique()} products have no label at all, "
        "but a product labelled for one query is usually unlabelled for another. `judged@10` shows how much "
        "that matters.",
        "",
        "## Classes",
        "",
        f"- `product_class` has {len(class_counts)} distinct classes once split on `|` "
        f"({multi:,} products list several; {nulls['product_class']:,} list none).",
        f"- Top 10: {', '.join(f'{c} ({n:,})' for c, n in class_counts.most_common(10))}.",
        f"- `query_class`: {len(set(labelled))} distinct, {len(query_classes) - len(labelled)} queries empty, "
        f"{sum(n == 1 for n in strata.values())} classes with one query.",
        f"- **Critical check:** of {len(labelled)} non-empty `query_class` values, {in_raw} match a raw "
        f"`product_class` string exactly and {in_split} match a split class. So `query_class` works as the gold "
        'label for query understanding with **no mapping**, and accuracy is reported as "vs labelled query '
        f'classes". The classes with no product are {", ".join(unmatched)}; they count as misses.',
        "",
        "## Attributes",
        "",
        f"`product_features` has {len(key_counts):,} distinct keys. The most common, by products carrying them:",
        "",
        "| key | products |",
        "|---|---|",
        *[f"| {k} | {n:,} |" for k, n in key_counts.most_common(30)],
        "",
        "Most of the top keys are compliance or logistics fields, and a shopper's query never mentions them. "
        "So query understanding's vocabulary is the shopper-facing groups in `wands/qu/attrs.py` (color, "
        "material, style, shape, pattern, room, size, theme), each of which pools several keys, such as "
        "`basecolor` and `topcolor`.",
        "",
        'Keys are not searchable text: `mirror : no` must not match the query "mirror". `feature_text` keeps '
        "values only, and drops yes/no flags and bare numbers.",
    ]
    return "\n".join(lines) + "\n"


def write_notes(path: Path = NOTES_PATH) -> Path:
    path.write_text(render(data.load(), git_sha()), encoding="utf-8", newline="\n")
    return path
