"""Per-stage latency of the online path, measured live: no cached vectors and no cached rerank scores."""

from __future__ import annotations

import time
from collections.abc import Callable

import numpy as np

from wands.retrievers.dense import QUERY_PREFIX, load_model
from wands.retrievers.fusion import FusionRetriever
from wands.types import Query


def percentiles(samples: list[float]) -> tuple[float, float]:
    p50, p95 = np.percentile(np.array(samples) * 1000, [50, 95])
    return float(p50), float(p95)


def timed(fn: Callable) -> tuple[object, float]:
    start = time.perf_counter()
    result = fn()
    return result, time.perf_counter() - start


def measure(
    world, bm25, dense, fusion: FusionRetriever, booster, scorer, texts: list[str], depth: int
) -> dict:
    """Run each stage for every query, in pipeline order, and time them separately."""
    model = load_model()
    stages: dict[str, list[float]] = {
        "bm25f": [],
        "query encoding": [],
        "dense dot product": [],
        "fusion": [],
        "qu lookup and boost": [],
        f"rerank top {depth}": [],
    }
    model.encode(QUERY_PREFIX + texts[0], normalize_embeddings=True)  # the first call loads lazily
    for text in texts:
        q = Query(text=text)
        lexical, t = timed(lambda q=q: bm25.search(q, fusion.depth))
        stages["bm25f"].append(t)
        vector, t = timed(lambda text=text: model.encode(QUERY_PREFIX + text, normalize_embeddings=True))
        stages["query encoding"].append(t)
        semantic, t = timed(lambda vector=vector: dense_search(dense, vector, fusion.depth))
        stages["dense dot product"].append(t)
        fused, t = timed(
            lambda lexical=lexical, semantic=semantic: fusion.fuse([lexical, semantic], fusion.depth)
        )
        stages["fusion"].append(t)
        boosted, t = timed(lambda q=q, fused=fused: booster.rescore(q, fused))
        stages["qu lookup and boost"].append(t)
        head = [hit.product_id for hit in boosted[:depth]]
        pairs = [(text, scorer.text(pid)) for pid in head]
        _, t = timed(lambda pairs=pairs: scorer.model.predict(pairs, batch_size=64, show_progress_bar=False))
        stages[f"rerank top {depth}"].append(t)
    return {stage: percentiles(samples) for stage, samples in stages.items()}


def dense_search(dense, vector: np.ndarray, k: int) -> list:
    from wands.retrievers.bm25f import top_k
    from wands.types import Hit

    scores = dense.embeddings @ vector
    return [Hit(product_id=int(dense.product_ids[i]), score=float(scores[i])) for i in top_k(scores, k)]


def render_latency(rows: dict, sha: str, n: int, cpu: str) -> str:
    lines = [
        "# Latency per stage",
        "",
        f"{n} dev queries on a laptop CPU ({cpu}), commit `{sha}`. Generated by `wands latency`. "
        "Each stage ran live and alone, one query at a time.",
        "",
        "| stage | p50 ms | p95 ms |",
        "|---|---|---|",
    ]
    lines += [f"| {stage} | {p50:.1f} | {p95:.1f} |" for stage, (p50, p95) in rows.items()]
    total50, total95 = sum(r[0] for r in rows.values()), sum(r[1] for r in rows.values())
    lines.append(f"| sum of stages | {total50:.1f} | {total95:.1f} |")
    return "\n".join(lines) + "\n"
