"""Score a run on a split, and render reports and comparison tables as markdown."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

from wands.eval.bootstrap import Delta, paired_bootstrap
from wands.eval.metrics import METRICS, score_query
from wands.eval.qrels import Qrels
from wands.eval.runfile import Run

RESULTS_DIR = Path("results")


@dataclass
class Scored:
    """Per-query metric arrays for one run, aligned on query_ids."""

    name: str
    split: str
    query_ids: list[int]
    scores: dict[str, np.ndarray]

    def mean(self, metric: str) -> float:
        return float(np.nanmean(self.scores[metric]))

    def count(self, metric: str) -> int:
        return int(np.count_nonzero(~np.isnan(self.scores[metric])))

    def means(self) -> dict[str, float]:
        return {metric: round(self.mean(metric), 6) for metric in METRICS}


def score_run(run: Run, qrels: Qrels, query_ids: list[int], name: str, split: str) -> Scored:
    """A query missing from the run scores as an empty ranking, so it can't flatter the mean."""
    rows = [score_query(run.get(qid, []), qrels.get(qid, {})) for qid in query_ids]
    scores = {m: np.array([row[m] for row in rows], dtype=float) for m in METRICS}
    return Scored(name, split, query_ids, scores)


def _cell(value: float) -> str:
    return "-" if np.isnan(value) else f"{value:.4f}"


def render_report(
    scored: Scored, sha: str, config: str, queries: dict[int, str], notes: list[str] | None = None
) -> str:
    lines = [
        f"# {scored.name} on {scored.split}",
        "",
        f"Config `{config}`, commit `{sha}`, {len(scored.query_ids)} queries. Generated by `wands eval`.",
        "",
        "| metric | mean | queries scored |",
        "|---|---|---|",
    ]
    lines += [f"| {m} | {scored.mean(m):.4f} | {scored.count(m)} |" for m in METRICS]
    if notes:
        lines += ["", *notes]
    lines += ["", "## Per query, worst first", "", "| query_id | query | " + " | ".join(METRICS) + " |"]
    lines.append("|---|---|" + "---|" * len(METRICS))
    for i in np.argsort(np.nan_to_num(scored.scores["ndcg@10"], nan=2.0), kind="stable"):
        qid = scored.query_ids[i]
        cells = " | ".join(_cell(scored.scores[m][i]) for m in METRICS)
        text = queries.get(qid, "").replace("|", "\\|")
        lines.append(f"| {qid} | {text} | {cells} |")
    return "\n".join(lines) + "\n"


def write_report(scored: Scored, text: str, sha: str, out_dir: Path = RESULTS_DIR) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{scored.name}_{scored.split}_{sha}.md"
    path.write_text(text, encoding="utf-8", newline="\n")
    return path


def fmt_delta(d: Delta) -> str:
    star = " *" if d.significant else ""
    return f"{d.delta:+.4f} [{d.low:+.4f}, {d.high:+.4f}]{star}"


def compare_table(rows: list[Scored], base: Scored, metrics: list[str]) -> str:
    """One row per run: mean of each metric, plus the bootstrap delta of ndcg@10 against `base`."""
    head = ["run", *metrics, f"delta ndcg@10 vs {base.name} [95% CI]"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for row in rows:
        if row.query_ids != base.query_ids:
            raise ValueError(f"{row.name} and {base.name} were not scored on the same queries")
        cells = [f"{row.mean(m):.4f}" for m in metrics]
        if row.name == base.name:
            delta = "base"
        else:
            delta = fmt_delta(paired_bootstrap(base.scores["ndcg@10"], row.scores["ndcg@10"]))
        lines.append("| " + " | ".join([f"`{row.name}`", *cells, delta]) + " |")
    return "\n".join(lines) + "\n"
