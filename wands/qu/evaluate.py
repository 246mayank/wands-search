"""Score query understanding directly, before asking whether it helps ranking."""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass

import numpy as np

from wands.eval.report import Scored
from wands.qu.cache import QUTable
from wands.qu.schema import OK
from wands.retrievers.booster import match_tokens


def candidate_recall(
    table: dict[str, list[str]], queries: dict[int, str], gold: dict[int, str], ids: list[int]
) -> dict:
    """Share of labelled queries whose gold class is in their candidate list: the LLM's ceiling."""
    labelled = [qid for qid in ids if gold[qid]]
    found = sum(gold[qid] in table[queries[qid]] for qid in labelled)
    sizes = [len(table[queries[qid]]) for qid in ids]
    return {
        "labelled": len(labelled),
        "found": found,
        "recall": found / len(labelled),
        "mean_size": float(np.mean(sizes)),
        "max_size": max(sizes),
        "missed": [(queries[q], gold[q]) for q in labelled if gold[q] not in table[queries[q]]],
    }


@dataclass
class ClassScores:
    labelled: int
    answered: int
    top1: int
    any3: int
    confusions: list[tuple[str, str, list[str]]]
    intents: Counter
    confidence: Counter
    attribute_queries: int
    attribute_values: int
    grounded_values: int


def class_scores(
    table: QUTable, queries: dict[int, str], gold: dict[int, str], ids: list[int]
) -> ClassScores:
    """Accuracy vs labelled query classes. A fallback answer counts as a miss, not as a skip."""
    labelled = answered = top1 = any3 = with_attrs = values = grounded = 0
    confusions = []
    intents: Counter = Counter()
    confidence: Counter = Counter()
    for qid in ids:
        qu, reason = table.lookup(queries[qid])
        if qu is not None:
            intents[qu.intent] += 1
            confidence[qu.confidence] += 1
            with_attrs += bool(qu.attributes)
            words = match_tokens(queries[qid])
            values += len(qu.attributes)
            grounded += sum(match_tokens(value) <= words for value in qu.attributes.values())
        if not gold[qid]:
            continue
        labelled += 1
        if reason != OK or qu is None:
            confusions.append((queries[qid], gold[qid], [reason]))
            continue
        answered += 1
        top1 += qu.product_classes[:1] == [gold[qid]]
        hit = gold[qid] in qu.product_classes
        any3 += hit
        if not hit:
            confusions.append((queries[qid], gold[qid], qu.product_classes))
    return ClassScores(
        labelled, answered, top1, any3, confusions, intents, confidence, with_attrs, values, grounded
    )


def render_scores(
    s: ClassScores, model: str, prompt: str, split: str, sha: str, fallbacks: dict, recall: dict
) -> str:
    def pct(n: int) -> str:
        return f"{n} ({n / s.labelled:.1%})"

    lines = [
        f"# Query understanding: `{model}`, prompt `{prompt}`, {split}",
        "",
        f"Commit `{sha}`. Generated by `wands qu eval`. Accuracy is vs labelled query classes, over "
        f"{s.labelled} labelled queries. A fallback counts as a miss.",
        "",
        "| measure | value |",
        "|---|---|",
        f"| candidate recall (ceiling) | {recall['found']}/{recall['labelled']} ({recall['recall']:.1%}) |",
        f"| mean candidates per query | {recall['mean_size']:.1f} (max {recall['max_size']}) |",
        f"| answered and valid | {pct(s.answered)} |",
        f"| top-1 class correct | {pct(s.top1)} |",
        f"| any of up to 3 classes correct | {pct(s.any3)} |",
        f"| fallbacks | {sum(fallbacks.values())} {fallbacks or ''} |",
        f"| queries with an attribute | {s.attribute_queries} |",
        f"| attribute values using only the query's words | {s.grounded_values}/{s.attribute_values} |",
        f"| intents | {dict(s.intents)} |",
        f"| confidence | {dict(s.confidence)} |",
        "",
        "## Misses (first 40)",
        "",
        "| query | labelled class | predicted |",
        "|---|---|---|",
    ]
    lines += [f"| {q} | {gold} | {', '.join(pred)} |" for q, gold, pred in s.confusions[:40]]
    return "\n".join(lines) + "\n"


def breakdown(base: Scored, boosted: Scored, groups: dict[int, str], min_size: int = 1) -> list[dict]:
    """Per group: mean NDCG@10 before and after, and how many queries moved each way."""
    a, b = base.scores["ndcg@10"], boosted.scores["ndcg@10"]
    rows = []
    for group in sorted(set(groups.values())):
        idx = [i for i, qid in enumerate(base.query_ids) if groups[qid] == group and not np.isnan(a[i])]
        if len(idx) < min_size:
            continue
        delta = b[idx] - a[idx]
        rows.append(
            {
                "group": group,
                "n": len(idx),
                "base": float(a[idx].mean()),
                "boosted": float(b[idx].mean()),
                "delta": float(delta.mean()),
                "helped": int((delta > 1e-9).sum()),
                "hurt": int((delta < -1e-9).sum()),
            }
        )
    return sorted(rows, key=lambda row: row["delta"] * row["n"], reverse=True)


def prediction_groups(
    table: QUTable, queries: dict[int, str], gold: dict[int, str], ids: list[int]
) -> dict[int, str]:
    """Each query by how the LLM's classes compare with its labelled class."""
    groups = {}
    for qid in ids:
        qu, _ = table.lookup(queries[qid])
        predicted = qu.product_classes if qu else []
        if not gold[qid]:
            groups[qid] = "no labelled class"
        elif predicted[:1] == [gold[qid]]:
            groups[qid] = "top class correct"
        elif gold[qid] in predicted:
            groups[qid] = "correct class in top 3"
        else:
            groups[qid] = "correct class not predicted"
    return groups


def start_groups(base: Scored) -> dict[int, str]:
    """Each query by how well the unboosted ranking already did it."""
    groups = {}
    for qid, value in zip(base.query_ids, base.scores["ndcg@10"], strict=True):
        if value < 0.5:
            groups[qid] = "started below 0.5"
        elif value < 0.8:
            groups[qid] = "started 0.5 to 0.8"
        else:
            groups[qid] = "started at 0.8 or above"
    return groups


def biggest_drops(base: Scored, boosted: Scored, n: int = 5) -> list[tuple[int, float, float]]:
    """The n queries that lost most, as (query id, before, after)."""
    a, b = base.scores["ndcg@10"], boosted.scores["ndcg@10"]
    order = np.argsort(np.nan_to_num(b - a, nan=0.0), kind="stable")[:n]
    return [(base.query_ids[i], float(a[i]), float(b[i])) for i in order]


def render_breakdown(rows: list[dict], title: str) -> str:
    lines = [
        f"## {title}",
        "",
        "| group | queries | base | boosted | delta | helped | hurt |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r['group']} | {r['n']} | {r['base']:.4f} | {r['boosted']:.4f} | {r['delta']:+.4f} "
            f"| {r['helped']} | {r['hurt']} |"
        )
    return "\n".join(lines) + "\n"
